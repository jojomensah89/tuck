import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Resolve the locked graph. Exclude build/dev edges; include runtime transitives.
const result = Bun.spawnSync(['cargo', 'metadata', '--locked', '--format-version', '1', '--manifest-path', 'src-tauri/Cargo.toml']);
if (result.exitCode !== 0) throw new Error(result.stderr.toString());
const meta = JSON.parse(result.stdout.toString());
const nodes = new Map(meta.resolve.nodes.map((n: any) => [n.id, n]));
const seen = new Set<string>();
function visit(id: string) {
  if (seen.has(id)) return;
  seen.add(id);
  const node: any = nodes.get(id);
  for (const d of node.deps) {
    if (d.dep_kinds.some((k: any) => k.kind === null)) visit(d.pkg);
  }
}
visit(meta.resolve.root);
const rows: string[] = [];
for (const p of meta.packages.filter((p: any) => seen.has(p.id) && p.id !== meta.resolve.root).sort((a: any,b: any) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))) {
  rows.push(`| Rust | ${p.name} | ${p.version} | ${p.license ?? (p.license_file ? 'See upstream licence file' : 'Not declared; review upstream')} |`);
}
const lock = Bun.JSON5.parse(readFileSync('bun.lock', 'utf8'));
const jsSeen = new Set<string>();
function jsVisit(name: string) {
  if (jsSeen.has(name)) return;
  jsSeen.add(name);
  const entry = lock.packages[name];
  if (!entry) throw new Error(`Missing lock entry: ${name}`);
  const manifest = JSON.parse(readFileSync(join('node_modules', name, 'package.json'), 'utf8'));
  const version = entry[0].slice(entry[0].lastIndexOf('@') + 1);
  if (manifest.version !== version) throw new Error(`Run bun install --frozen-lockfile: ${name}`);
  rows.push(`| JS | ${name} | ${version} | ${manifest.license ?? 'Not declared; review upstream'} |`);
  for (const child of Object.keys(entry[2]?.dependencies ?? {})) jsVisit(child);
}
for (const name of Object.keys(lock.workspaces[''].dependencies).sort()) jsVisit(name);
const file = 'THIRD_PARTY_NOTICES.md';
const old = readFileSync(file, 'utf8');
const begin = '<!-- dependencies:start -->', end = '<!-- dependencies:end -->';
const start = old.indexOf(begin), finish = old.indexOf(end);
if (start < 0 || finish < start) throw new Error('Dependency markers missing');
const generated = `${begin}

Generated by scripts/third-party-notices.ts from cargo metadata --locked and bun.lock plus installed package manifests. Runtime transitive dependencies are included across Cargo target platforms; build and dev edges are excluded. Licence expressions retain upstream alternatives. This inventory is not a replacement for upstream licence texts.

| Ecosystem | Package | Version | Licence |
| --- | --- | --- | --- |
${rows.join('\n')}

`;
writeFileSync(file, old.slice(0,start) + generated + old.slice(finish));
